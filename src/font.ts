/**
 * Pixel fonts for the name banner. Each glyph is a list of rows,
 * `#` for a lit pixel. Two terminal rows hold one cell of pixels
 * each via half-block characters, so a 7-row glyph is 4 rows tall.
 */
export interface PixelFont {
	readonly width: number;
	readonly height: number;
	readonly glyphs: Readonly<Record<string, readonly string[]>>;
}

export interface Pixel {
	readonly x: number;
	readonly y: number;
}

