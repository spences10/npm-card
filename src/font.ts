const SPACE_WIDTH = 2;

/** Width in pixels of `text` set in `font`, with 1px between glyphs. */
export function text_width(text: string, font: PixelFont): number {
	let width = 0;
	for (const ch of text.toUpperCase()) {
		width += (ch === ' ' ? SPACE_WIDTH : font.width) + 1;
	}
	return Math.max(width - 1, 0);
}

/** True when every character in `text` has a glyph in `font`. */
export function can_set(text: string, font: PixelFont): boolean {
	return Array.from(text.toUpperCase()).every(
		(ch) => ch === ' ' || ch in font.glyphs,
	);
}

/** Lit pixels for `text`, origin top-left. */
export function set_text(text: string, font: PixelFont): Pixel[] {
	const pixels: Pixel[] = [];
	let left = 0;
	for (const ch of text.toUpperCase()) {
		if (ch === ' ') {
			left += SPACE_WIDTH + 1;
			continue;
		}
		const glyph = font.glyphs[ch] ?? [];
		glyph.forEach((row, y) => {
			Array.from(row).forEach((value, x) => {
				if (value === '#') pixels.push({ x: left + x, y });
			});
		});
		left += font.width + 1;
	}
	return pixels;
}
